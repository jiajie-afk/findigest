/**
 * First character of keyword → original rule indices (in ascending order).
 * Do not match solely via name[0]: keywords can appear mid-name
 * (e.g. name "中国平安" vs keyword "平安").
 */
const RULE_INDEX_BY_FIRST_CHAR = new Map()
for (let i = 0; i < NAME_RULES.length; i++) {
  const ch = NAME_RULES[i][0][0]
  let bucket = RULE_INDEX_BY_FIRST_CHAR.get(ch)
  if (!bucket) {
    bucket = []
    RULE_INDEX_BY_FIRST_CHAR.set(ch, bucket)
  }
  bucket.push(i)
}

/**
 * @param {string|number|null|undefined} code
 * @param {string|null|undefined} name
 * @returns {string}
 */
export function getIndustry(code, name) {
  name = name || getStockName(code) || ''
  code = String(code || '')

  const byCode = industryByCode(code)
  if (byCode) return byCode

  // Mark candidate rule indices whose keyword[0] appears somewhere in name.
  const candidate = new Uint8Array(NAME_RULES.length)
  const seenChars = new Set()
  for (let i = 0; i < name.length; i++) {
    const ch = name[i]
    if (seenChars.has(ch)) continue
    seenChars.add(ch)
    const bucket = RULE_INDEX_BY_FIRST_CHAR.get(ch)
    if (!bucket) continue
    for (let j = 0; j < bucket.length; j++) candidate[bucket[j]] = 1
  }

  // Test marked rules in original order (first match wins).
  // Short geo/brand tokens must not invent a bank/broker: 「江苏雷利」≠城商行，「长江电力」≠券商.
  // Full names (中国银河、申万宏源、中银香港) are long enough to trust without 证券/银行 suffix.
  const BANK_LIKE = new Set(['国有大行', '股份制银行', '城商行', '农商行'])
  const BROKER_LIKE = new Set(['头部券商', '中型券商', '中小券商'])
  for (let i = 0; i < NAME_RULES.length; i++) {
    if (!candidate[i]) continue
    const kw = NAME_RULES[i][0]
    if (name.indexOf(kw) < 0) continue
    const ind = NAME_RULES[i][1]
    if (BANK_LIKE.has(ind) && kw.length < 4 && !/银行|农商/.test(name)) continue
    if (BROKER_LIKE.has(ind) && kw.length < 4 && !/证券|券商/.test(name)) continue
    return ind
  }

  // High-confidence suffix / token fallbacks when keyword table misses
  if (name) {
    // Delisted / ST shells — keep generic, don't invent a fake industry story
    if (/^退市|退$/.test(name) || /\*ST|ST[\u4e00-\u9fff]/.test(name)) {
      /* fall through to 其他 */
    } else {
      if (/农商银行|农村商业银行/.test(name)) return '农商行'
      if (/银行/.test(name)) return '城商行'
      if (/证券/.test(name)) return '中型券商'
      if (/保险|人寿|人保|太保/.test(name)) return '综合保险'
      if (/信托/.test(name)) return '中小券商'
      if (/疫苗/.test(name)) return '疫苗'
      if (/血液|血制品/.test(name)) return '血液制品'
      if (/生物(?!柴油)/.test(name)) return '生物创新药'
      if (/药业|制药|医药|中药/.test(name)) return /中药/.test(name) ? '中药创新' : '化学创新药'
      if (/医疗|医院|诊疗|镜片|眼科/.test(name)) return /镜片|眼科/.test(name) ? '眼科医疗' : '医疗服务'
      if (/白酒|酒业|酿酒|酱酒/.test(name)) return '区域白酒'
      if (/乳业|乳品|奶业|倍健/.test(name)) return /倍健/.test(name) ? '休闲食品' : '液态奶'
      if (/旅游|景区|酒店|餐饮|捞|火锅|茶饮/.test(name)) return /酒店/.test(name) ? '酒店' : '景区'
      if (/高速|公路|路桥/.test(name)) return '基建'
      if (/水电|水力/.test(name)) return '水电'
      if (/火电|电力|发电|风电|光伏运营/.test(name)) return '火电'
      if (/煤炭|煤业|焦煤/.test(name)) return '动力煤'
      if (/钢铁|特钢|钢管|莱钢|宝钢|鞍钢/.test(name)) return '普钢'
      if (/铜业|铝业|锌业|矿业|有色|兰铝/.test(name)) return '工业金属'
      if (/黄金|白银/.test(name)) return '贵金属'
      if (/石油|海油|中海油|石化/.test(name)) return '基础化工'
      if (/地产|置业|房地产|海外发展|绿城|金隅/.test(name)) return '住宅开发'
      if (/物业/.test(name)) return '物业管理'
      if (/航空|机场|东航|国航|南航/.test(name)) return '客运航空'
      if (/港口|海运|航运/.test(name)) return '航运'
      if (/光模块|光通信|光纤|光缆|旭创|天孚|通信|瀚讯/.test(name)) return '通信设备'
      if (/超媒|传媒|文娱|影视|动漫|游戏|阅文|芒果/.test(name)) return /游戏|阅文/.test(name) ? '游戏' : '影视'
      if (/网络|软件|信息|数据|云|互联|导航|招标/.test(name)) return 'SaaS云计算'
      if (/半导体|芯片|微电|硅片|国科微|扬杰|卓胜/.test(name)) return '芯片设计'
      if (/电路|电子|电连|精测|安科瑞|民德|弘信|秋田微/.test(name)) return '通信设备'
      if (/电池|锂电|储能/.test(name)) return '动力电池'
      if (/汽车|轿车|客车|智驱/.test(name)) return '传统车企'
      if (/家电|电器|澳柯玛/.test(name)) return '白电'
      if (/服饰|服装|鞋|红豆|滔搏|运动/.test(name)) return '休闲服饰'
      if (/水泥|玻璃|建材|巨石/.test(name)) return '水泥'
      if (/化工|化学|化能|龙盛|华鲁|巨化|金发|嘉化/.test(name)) return '基础化工'
      if (/饲料|养殖|种业|农业|米业|好当家/.test(name)) return '养殖'
      if (/环保|水务|污水|固废|燃气|节能|维尔利|博世科|国祯/.test(name)) return '水处理'
      if (/军工|航天|航空科技|兵器|新研/.test(name)) return '军工电子'
      if (/光学|舜宇|丘钛|瑞声|镜头/.test(name)) return '消费电子'
      if (/白酒|调味|酿造|恒和/.test(name)) return '复合调味品'
      if (/零售|甄选|超市|百货/.test(name)) return '电商零售'
      if (/三一|工程机械|机械/.test(name)) return '工程机械'
      if (/金风|风电设备/.test(name)) return '新能源发电'
      if (/控股|集团|国际/.test(name) && /中国|北京|统一|万洲|康师傅|海底捞|九毛|升能|思摩尔|美高梅|雅迪|JS环球/.test(name)) {
        if (/统一|康师傅|万洲|海底捞|九毛|升能/.test(name)) return '休闲食品'
        if (/雅迪/.test(name)) return '传统车企'
        if (/思摩尔/.test(name)) return '消费电子'
        if (/美高梅/.test(name)) return '景区'
        if (/百度/.test(name)) return '社交内容'
      }
      // Broad tech / manufacturing catch-alls (after specific rules)
      // NOTE: do NOT match bare「股份」— nearly every A-share name has it.
      if (/技术|科技|智能|仪器|设备|制造|微$|电子/.test(name)) {
        if (/电子|电路|半导体|芯片|光|通信/.test(name)) return '通信设备'
        if (/材料|新材|化工/.test(name)) return '新材料'
        return '专用设备'
      }
      if (/材料|新材/.test(name)) return '新材料'
      if (/文化|传媒/.test(name)) return '影视'
    }
  }

  // Code-based fallbacks (preserved from original)
  if (code.length <= 5) return '港股其他'
  return '其他'
}

